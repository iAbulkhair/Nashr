export type StaffError = keyof (typeof SW)["en"]["errors"];
/** The words for an error code a staff route answered, or the generic failure. */
export function staffError(lang: Lang, error: unknown): string {
  const E = SW[lang].errors as Record<string, string>;
  return typeof error === "string" && Object.prototype.hasOwnProperty.call(E, error) ? E[error] : E.failed;
}
